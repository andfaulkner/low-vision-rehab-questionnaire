#!/usr/bin/env python3
"""Build paper/manuscript_rendered.docx from the rendered Markdown.

    python3 -I paper/build_docx.py            # run from the repository root

Steps: take paper/manuscript_rendered.md (generated by cite.py render), splice the numbered
reference list from paper/references.md under its "## References" heading, embed each figure
image above its caption, drop the box comment markers, and run pandoc. Re-run after every
`cite.py render`. Needs pandoc on the PATH; nothing here edits the Markdown sources."""
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'paper', 'manuscript_rendered.md')
REFS = os.path.join(ROOT, 'paper', 'references.md')
OUT = os.path.join(ROOT, 'paper', 'manuscript_rendered.docx')

s = open(SRC, encoding='utf-8').read()
refs = open(REFS, encoding='utf-8').read()
refs = re.sub(r'^## References\s*', '', refs.strip(), count=1).strip()
if not re.search(r'^1\. ', refs, re.M):
    sys.exit('paper/references.md holds no numbered entries; run cite.py render first')

placeholder = '<!-- generated by cite.py render; see paper/references.md -->'
if placeholder not in s:
    sys.exit('placeholder comment under "## References" not found in manuscript_rendered.md')
s = s.replace(placeholder, refs)
s = s.replace('<!-- box:start -->\n', '').replace('<!-- box:end -->\n', '')


def fig(m):
    line = m.group(0)
    f = re.search(r'\(File: ([^)]+?)\.\)', line)
    if not f:
        return line
    caption = line.replace(f.group(0), '').rstrip()
    return '![](%s)\n\n%s' % (f.group(1), caption)


s = re.sub(r'^\*\*Figure \d+\.\*\*.*$', fig, s, flags=re.M)

with tempfile.NamedTemporaryFile('w', suffix='.md', delete=False, encoding='utf-8', dir=os.path.join(ROOT, 'paper')) as fh:
    fh.write(s)
    tmp = fh.name
try:
    subprocess.run(['pandoc', tmp, '-f', 'markdown', '-t', 'docx', '--resource-path=' + ROOT, '-o', OUT], check=True, cwd=ROOT)
finally:
    os.unlink(tmp)
n_refs = len(re.findall(r'^\d+\. ', refs, re.M))
print('wrote', os.path.relpath(OUT, ROOT), 'with', n_refs, 'references and', s.count('![]('), 'embedded figures')
